"""Step 5 — grounded insights: Observation → Evidence → Interpretation → Limitation → Next step."""
from __future__ import annotations

import html

import streamlit as st

from ai import assistant, llm
from components import ui
from core import state

if not ui.require_data("generate insights"):
    st.stop()

ui.page_header("Step 5 · Insights", "AI insights & data story",
               "Findings are produced by deterministic rules from the computed analysis. A language model, if configured, may only rephrase them.")
ui.synthetic_notice()

r = state.results()
ins = r["insights"]
cfg = llm.get_config()

c1, c2 = st.columns([3, 1], vertical_alignment="center")
with c1:
    if cfg:
        st.html(f'<span class="ds-pill ok">LLM connected · {html.escape(cfg.model)}</span> '
                '<span style="font-size:.85rem;color:#697468">Narrative wording may be polished by the model; numbers are verified against the facts.</span>')
    else:
        st.html('<span class="ds-pill muted">Rule-based mode</span> '
                '<span style="font-size:.85rem;color:#697468">No LLM key configured — insights and narrative are fully deterministic. See the README to enable an LLM.</span>')
with c2:
    regenerate = st.button("Write narrative", type="primary", icon=":material/auto_stories:", width="stretch",
                           help="Builds the story from the current findings. Uses the LLM only if one is configured.")

if regenerate:
    with st.spinner("Writing the data story from verified findings…"):
        st.session_state["narrative"] = assistant.polished_narrative(r)

story = st.session_state.get("narrative")
st.subheader("Data story")
if story:
    with st.container(border=True):
        st.markdown(story["text"])
        st.caption("Written by the configured LLM from verified facts; every figure was checked against the computed analysis."
                   if story["mode"] == "llm" else "Generated by rules from the computed analysis (no language model involved).")
    if story.get("note"):
        st.warning(story["note"], icon=":material/shield:")
else:
    ui.callout("Choose “Write narrative” to turn the findings below into a short story. "
               "It is rebuilt whenever the dataset, target or models change.", "na")

st.subheader(f"Findings ({len(ins)})")
cats = sorted({i["category"] for i in ins})
pick = st.segmented_control("Filter", ["All"] + cats, default="All", key="ins_filter", label_visibility="collapsed") or "All"
badge = {"warning": ("Needs attention", "syn"), "attention": ("Review", "syn"), "info": ("Info", "muted")}
for i in ins:
    if pick != "All" and i["category"] != pick:
        continue
    e = html.escape
    label, cls = badge[i["severity"]]
    with st.container(border=True):
        st.html(
            f'<div class="ds-insight"><div class="cat">{e(i["category"])} &nbsp;<span class="ds-pill {cls}">{label}</span></div>'
            f'<h4>{e(i["title"])}</h4><dl>'
            f'<dt>Observation</dt><dd>{e(i["observation"])}</dd>'
            f'<dt>Evidence</dt><dd><ul>{"".join(f"<li>{e(x)}</li>" for x in i["evidence"])}</ul></dd>'
            f'<dt>Interpretation</dt><dd>{e(i["interpretation"])}</dd>'
            f'<dt>Limitation</dt><dd>{e(i["limitation"])}</dd>'
            f'<dt>Next step</dt><dd>{e(i["next_step"])}</dd>'
            f'<dt>Source</dt><dd style="color:#697468">{e(i["source"])}</dd></dl></div>')

if not r.get("modeling"):
    ui.callout("Model-comparison and feature-importance findings appear here after you train models on the Modeling step.", "na")
